ROOT=Path(__file__).resolve().parents[1]


def freeze_recovery(trial):
    name='scripts/rehearse_document_result_restore.py';raw=(ROOT/name).read_bytes()
    for node in ast.walk(ast.parse(raw)):
        if isinstance(node,ast.ImportFrom) and node.module:
            child=node.module.replace('.','/')+'.py'
            if (ROOT/child).is_file() and child not in trial.frozen:
                raise FeedPgTrialError('Recovery dependency is not frozen')
    destination=trial.proof/'inputs'/name
    with destination.open('xb') as stream:stream.write(raw)
    destination.chmod(0o600);trial.frozen[name]=raw
    row={'path':name,'bytes':len(raw),'sha256':sha256(raw).hexdigest()}
    trial.source_bindings.append(row);trial.record('RECOVERY_SOURCE_BINDINGS',[row])


class OwnedRestoreDatabase:
    def __init__(self,trial):
        self.trial=trial;self.name='tf_document_restore_'+trial.suffix.lower().replace('-','_');self.oid=None
        if re.fullmatch('[a-z0-9_]{1,63}',self.name) is None:raise FeedPgTrialError('Restore database intent invalid')
        trial.record('RESTORE_DATABASE_INTENT',{'name':self.name,'newOwnedClusterOnly':True,'primaryChanged':False})

    def current(self):
        if self.name!='tf_document_restore_'+self.trial.suffix.lower().replace('-','_') or re.fullmatch('[a-z0-9_]{1,63}',self.name) is None:
            raise FeedPgTrialError('Restore database intent changed')
        self.trial.inspect()
        result=self.trial.query("select jsonb_build_object('oid',oid::bigint,'name',datname,'owner',pg_get_userbyid(datdba)) from pg_database where datname="+_literal(self.name)+';')
        if not result.stdout.strip():return None
        value=json.loads(result.stdout)
        if (type(value) is not dict or set(value)!={'oid','name','owner'} or value['name']!=self.name or value['owner']!='postgres'
                or type(value['oid']) is not int or value['oid']<=0 or (self.oid is not None and value['oid']!=self.oid)):
            raise FeedPgTrialError('Restore database identity invalid')
        return value

    def create(self):
        if self.current() is not None:raise FeedPgTrialError('Restore database was not absent')
        # Name is generated by the custodian and restricted to ASCII identifier
        # characters, never received from source/request/environment material.
        self.trial.query('create database "'+self.name+'" template template0;')
        value=self.current()
        if value is None:raise FeedPgTrialError('Restore database acknowledgement unavailable')
        self.oid=value['oid'];self.trial.record('RESTORE_DATABASE_CREATED',value)

    def query(self,statement,*,allowed=False,single_transaction=False):
        if self.oid is None or self.current() is None:raise FeedPgTrialError('Owned restore database unavailable')
        args=['docker','exec','-i',self.trial.identity,BIN+'psql','-h','/tmp','-U','postgres','-d',self.name,
            '-X','-qAt','-v','ON_ERROR_STOP=1']
        if single_transaction:args.extend(['--single-transaction','--file=-'])
        result=self.trial.run(args,payload=statement if type(statement) is bytes else statement.encode('utf8'),allowed=allowed,timeout=20)
        if self.current() is None:raise FeedPgTrialError('Restore database disappeared after request')
        return result


def access_observation(query):
    sql="""begin isolation level repeatable read read only;select jsonb_build_object(
      'publicSchema',(select count(*) from pg_namespace n cross join lateral aclexplode(coalesce(n.nspacl,acldefault('n',n.nspowner))) a where n.nspname='tf_feed_rehearsal' and a.grantee=0),
      'publicTable',(select count(*) from pg_class c join pg_namespace n on n.oid=c.relnamespace cross join lateral aclexplode(coalesce(c.relacl,acldefault('r',c.relowner))) a where n.nspname='tf_feed_rehearsal' and c.relkind='r' and a.grantee=0),
      'publicFunction',(select count(*) from pg_proc p join pg_namespace n on n.oid=p.pronamespace cross join lateral aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a where n.nspname='tf_feed_rehearsal' and a.grantee=0),
      'rlsTables',(select count(*) from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='tf_feed_rehearsal' and c.relkind='r' and c.relrowsecurity),
      'tables',(select count(*) from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='tf_feed_rehearsal' and c.relkind='r'));commit;"""
    return json.loads(query(sql).stdout)


def recovered(query,request):
    result=query(invented_document_result_read_statement(request))
    raw=committed_pg_json(result.stdout,result.stderr,result.returncode)
    return parse_stored_invented_document_result(raw,request,observed_at=datetime.now(timezone.utc)),raw


def cases(trial):
    first=result_request(trial);value,raw=store(trial,first)
    second=result_request(trial,body='Invented original\n  Second exact source result.\r\nOther metadata.'.encode())
    value2,raw2=store(trial,second)
    before_acl=access_observation(trial.query)
    expected={'publicSchema':0,'publicTable':0,'publicFunction':0,'rlsTables':5,'tables':5}
    trial.check('source_private_acl_rls',before_acl==expected)
    trial.inspect()
    # Include explicit REVOKEs/ACLs. --no-privileges would lose function PUBLIC
    # EXECUTE revocations and is deliberately not used for this recovery proof.
    dump=trial.run(['docker','exec',trial.identity,BIN+'pg_dump','-h','/tmp','-U','postgres','-d','postgres',
        '--format=p','--schema=tf_feed_rehearsal','--no-owner'],timeout=20)
    if dump.stderr or not dump.stdout or len(dump.stdout)>131072:raise FeedPgTrialError('Bounded logical dump unavailable')
    trial.check('dump_contains_private_schema_acl_and_rls',b'ENABLE ROW LEVEL SECURITY' in dump.stdout and b'REVOKE ALL ON FUNCTION' in dump.stdout and b'FROM PUBLIC' in dump.stdout)
    trial.check('dump_has_no_database_role_creation',not any(value in dump.stdout.upper() for value in (b'\nCREATE DATABASE',b'\nCREATE ROLE',b'\nALTER ROLE')))
    trial.record('LOGICAL_DUMP',{'bytes':len(dump.stdout),'sha256':sha256(dump.stdout).hexdigest(),
        'schema':'tf_feed_rehearsal','includesPrivileges':True,'noOwnerRewrite':True,'inventedOnly':True})
    target=OwnedRestoreDatabase(trial);target.create()
    empty=target.query("select count(*) from pg_namespace where nspname='tf_feed_rehearsal';")
    trial.check('fresh_restore_database_empty',empty.stdout.strip()==b'0')
    # Successful dump application plus an injected error, all inside psql's one
    # transaction. Failure must leave neither schema nor partially copied rows.
    failed=target.query(dump.stdout+b'\nselect 1/0;\n',single_transaction=True,allowed=True)
    trial.check('injected_restore_failure_refuses',failed.returncode!=0 and b'division by zero' in failed.stderr)
    empty=target.query("select count(*) from pg_namespace where nspname='tf_feed_rehearsal';")
    trial.check('failed_restore_is_transactionally_empty',empty.stdout.strip()==b'0')
    result=target.query(dump.stdout,single_transaction=True)
    trial.check('exact_logical_restore_clean',result.returncode==0 and not result.stderr)
    one,one_raw=recovered(target.query,first);two,two_raw=recovered(target.query,second)
    trial.check('restored_original_result_identity_bytes_and_event',one==value and one_raw==raw and two==value2 and two_raw==raw2)
    trial.check('restored_private_acl_rls',access_observation(target.query)==before_acl==expected)
    # Exact original database remains unchanged and independently readable.
    old,old_raw=inspect_result(trial,first)
    trial.check('source_result_not_mutated',old==value and old_raw==raw)
    trial.stop();trial.start()
    restarted,restarted_raw=recovered(target.query,first)
    trial.check('restored_database_actual_restart',restarted==value and restarted_raw==raw)
    trial.check('restored_acl_survives_restart',access_observation(target.query)==expected)
    final_identity=target.current();trial.record('RESTORE_DATABASE_FINAL',final_identity)
    return {'restoreDatabase':final_identity,'logicalDumpSHA256':sha256(dump.stdout).hexdigest(),
        'firstOperationId':first.operation_id,'secondOperationId':second.operation_id,'sameMachineOnly':True,
        'offHostOrNasAccepted':False,'powerLossAccepted':False,'restrictedApplicationRoleAccepted':False}


def main():
    if sys.argv[1:]:raise FeedPgTrialError('Fixed invented result restore takes no arguments')
    os.umask(0o077);trial=FreshFeedPostgres()
    try:
        freeze_additional(trial);freeze_recovery(trial);trial.create()
        trial.query("begin;set local statement_timeout='10s';"+trial.frozen['tests/fixtures/invented_document_results.sql'].decode('utf8')+'commit;')
        result=cases(trial)
        trial.record('DOCUMENT_RECOVERY_RESULT',{'state':'PASS_INVENTED_DOCUMENT_LOGICAL_RECOVERY','assertions':trial.assertions,
            'identities':result,'sourceRequests':0,'modelCalls':0,'primaryChanged':False,'publicationEnabled':False})
    except BaseException as failure:
        trial.record('DOCUMENT_RECOVERY_FAILURE',{'state':'held','exceptionClass':type(failure).__name__,'evidenceRetained':True})
        raise
    finally:
        try:trial.stop()
        finally:
            try:trial.stop_initializer()
            finally:trial.verify_sources('FINAL_RECOVERY')
        if trial.identity is not None:trial.record('RECOVERY_FINAL_OWNED_STATE',trial.inspect())
    print(json.dumps({'proof':str(trial.proof),'assertions':len(trial.assertions),'state':'PASS_INVENTED_DOCUMENT_LOGICAL_RECOVERY','primaryChanged':False}))


if __name__=='__main__':main()
